def _safe_float(value: Any) -> float | None:
    if value is None:
        return None
    if isinstance(value, bool):
        return float(value)
    if isinstance(value, (int, float)):
        return float(value)
    try:
        parsed = float(str(value).strip())
    except (TypeError, ValueError):
        return None
    if math.isfinite(parsed):
        return parsed
    return None


def _read_json(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8") as fh:
        payload = json.load(fh)
    if isinstance(payload, Mapping):
        return dict(payload)
    raise TypeError(f"invalid JSON payload in {path}: expected object")


def _to_csv_value(value: Any) -> str | int | float | bool:
    if value is None:
        return ""
    if isinstance(value, bool):
        return value
    if isinstance(value, float):
        return value if not math.isnan(value) else ""
    if isinstance(value, (int, str)):
        return value
    return str(value)


def _to_html_value(value: Any, precision: int = 6) -> str:
    if value is None or value == "":
        return "&ndash;"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return f"{value}"
    if isinstance(value, float):
        if not math.isfinite(value):
            return "&ndash;"
        if value == 0:
            return "0"
        return f"{value:.{precision}f}".rstrip("0").rstrip(".")
    return html.escape(str(value))


def _to_html_label(value: Any) -> str:
    if value is None or value == "":
        return "&ndash;"
    if value is True:
        return "yes"
    if value is False:
        return "no"
    return html.escape(str(value))


def _risk_badge_class(level: str) -> str:
    if level == "low":
        return "risk-low"
    if level == "medium":
        return "risk-medium"
    if level == "high":
        return "risk-high"
    return "risk-unknown"


def _metric_preferred_direction(lower_is_better: bool) -> str:
    return "smaller is better" if lower_is_better else "larger is better"


def _safe_float_sort(value: Any) -> float:
    if isinstance(value, bool):
        return float(value)
    if isinstance(value, (int, float)) and math.isfinite(float(value)):
        return float(value)
    return float("inf")


def _metric_aliases(key: str) -> tuple[str, ...]:
    return KEY_ALIASES.get(key, (key,))


def _metric_from_section(section: Mapping[str, Any], metric_key: str) -> float | None:
    metrics = section.get("metrics", {})
    if not isinstance(metrics, Mapping):
        return None
    for candidate in _metric_aliases(metric_key):
        value = _safe_float(metrics.get(candidate))
        if value is not None:
            return value
    return None


def _flatten_sections(bundle: Mapping[str, Any]) -> Mapping[str, Mapping[str, Any]]:
    sections = bundle.get("sections")
    if isinstance(sections, Mapping):
        return {str(k): dict(v) for k, v in sections.items() if isinstance(v, Mapping)}
    return {}


def _collect_metric_comparison_rows(
    metrics_sections: Mapping[str, Mapping[str, Any]],
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    metric_rows: list[dict[str, Any]] = []
    summary_rows: list[dict[str, Any]] = []

    for metric_key, family, metric_label, lower_is_better, description in STRUCTURE_METRICS:
        direction_values: dict[str, float | None] = {}
        for direction, section_name in COMPARE_DIRECTIONS:
            section = metrics_sections.get(section_name, {})
            status = section.get("status", "missing")
            source_file = section.get("source_file")
            value = _metric_from_section(section, metric_key)
            direction_values[direction] = value
            metric_rows.append(
                {
                    "record_type": "metric_point",
                    "metric_family": family,
                    "metric_key": metric_key,
                    "metric_label": metric_label,
                    "direction": direction,
                    "run_section": section_name,
                    "value": value,
                    "value_type": type(value).__name__ if value is not None else "missing",
                    "lower_is_better": lower_is_better,
                    "status": status,
                    "source_file": source_file if source_file is not None else "",
                    "tooltip_id": metric_key,
                    "description": description,
                }
            )

        synth_to_val = direction_values.get("synth->val")
        synth_to_hold = direction_values.get("synth->hold")
        hold_to_val = direction_values.get("hold->val")

        # Derived indicators:
        # 1) How much additional variation appears in synth->val relative to natural hold->val variation.
        # 2) Whether the synthetic distribution drift from hold to val is larger than synthetic->hold.
        derived_abs_gap = None
        relative_gap = None
        synthetic_generalization = None
        risk_level = "unknown"
        if (
            synth_to_val is not None
            and hold_to_val is not None
        ):
            derived_abs_gap = abs(synth_to_val - hold_to_val)
            if hold_to_val != 0:
                relative_gap = derived_abs_gap / abs(hold_to_val)
            if lower_is_better:
                if relative_gap is None:
                    risk_level = "unknown"
                elif relative_gap <= 0.10:
                    risk_level = "low"
                elif relative_gap <= 0.25:
                    risk_level = "medium"
                else:
                    risk_level = "high"
            else:
                if relative_gap is None:
                    risk_level = "unknown"
                elif relative_gap <= 0.10:
                    risk_level = "low"
                elif relative_gap <= 0.25:
                    risk_level = "medium"
                else:
                    risk_level = "high"

        if (
            synth_to_val is not None
            and synth_to_hold is not None
            and hold_to_val is not None
        ):
            synthetic_generalization = (synth_to_val - hold_to_val) - (synth_to_hold - hold_to_val)

        summary_rows.append(
            {
                "record_type": "comparison_summary",
                "metric_family": family,
                "metric_key": metric_key,
                "metric_label": metric_label,
                "lower_is_better": lower_is_better,
                "tooltip_id": metric_key,
                "synth_to_val": synth_to_val,
                "synth_to_hold": synth_to_hold,
                "hold_to_val": hold_to_val,
                "abs_gap_to_hold_val": derived_abs_gap,
                "relative_gap_to_hold_val": relative_gap,
                "generalization_shift": synthetic_generalization,
                "risk_level": risk_level,
                "description": description,
            }
        )

    return metric_rows, summary_rows


def _resolve_bundle_path(run_dir: Path, value: str) -> Path | None:
    candidate = Path(value)
    if candidate.exists():
        return candidate

    if not candidate.is_absolute():
        alt = run_dir / candidate
        if alt.exists():
            return alt
        alt = Path.cwd() / candidate
        if alt.exists():
            return alt
        script_root = Path(__file__).resolve().parent.parent
        alt = script_root / candidate
        if alt.exists():
            return alt
        for ancestor in (run_dir.parent, run_dir.parent.parent):
            alt = ancestor / candidate
            if alt.exists():
                return alt
    return candidate


def _collect_training_time_series_rows(
    run_dir: Path,
    training_sections: Mapping[str, Mapping[str, Any]],
) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []

    for run_section, section in sorted(training_sections.items()):
        artifact_name = section.get("artifact_name")
        if artifact_name not in TRAINING_RECORDS:
            continue
        status = section.get("status", "unknown")
        if status != "ok":
            continue
        source_file = section.get("source_file")
        if source_file is None:
            continue

        source_path = _resolve_bundle_path(run_dir, source_file)
        if not source_path.exists():
            continue

        if artifact_name in {"loss_point", "scalars"}:
            if artifact_name == "loss_point":
                pass

        if artifact_name == "loss":
            with source_path.open("r", encoding="utf-8", newline="") as fh:
                reader = csv.DictReader(fh)
                for row_idx, row in enumerate(reader):
                    if row is None:
                        continue
                    epoch = row.get("epoch", row_idx)
                    for metric_name, metric_raw in row.items():
                        if metric_name == "epoch":
                            continue
                        value = _safe_float(metric_raw)
                        rows.append(
                            {
                                "record_type": "loss_point",
                                "run_section": run_section,
                                "artifact_name": artifact_name,
                                "metric_name": metric_name,
                                "step_axis": "epoch",
                                "step": epoch,
                                "value": value,
                                "value_type": type(value).__name__ if value is not None else "missing",
                                "status": status,
                                "source_file": source_file,
                            }
                        )
            continue

        if artifact_name == "scalars":
            with source_path.open("r", encoding="utf-8", newline="") as fh:
                reader = csv.DictReader(fh)
                for row in reader:
                    if row is None:
                        continue
                    step = row.get("step")
                    tag = row.get("tag", "")
                    value = _safe_float(row.get("value"))
                    rows.append(
                        {
                            "record_type": "scalar_point",
                            "run_section": run_section,
                            "artifact_name": artifact_name,
                            "metric_name": str(tag),
                            "step_axis": "step",
                            "step": step,
                            "value": value,
                            "value_type": type(value).__name__ if value is not None else "missing",
                            "status": status,
                            "source_file": source_file,
                        }
                    )
            continue

        if artifact_name == "log":
            events = section.get("metrics", {}).get("events", [])
            if not isinstance(events, list):
                continue
            for event in events:
                if not isinstance(event, Mapping):
                    continue
                epoch = event.get("epoch")
                if epoch is None:
                    continue
                rows.append(
                    {
                        "record_type": "log_point",
                        "run_section": run_section,
                        "artifact_name": artifact_name,
                        "metric_name": "train_metric",
                        "step_axis": "epoch",
                        "step": epoch,
                        "value": _safe_float(event.get("train_metric")),
                        "value_type": "float",
                        "status": status,
                        "source_file": source_file,
                    }
                )
                rows.append(
                    {
                        "record_type": "log_point",
                        "run_section": run_section,
                        "artifact_name": artifact_name,
                        "metric_name": "val_metric",
                        "step_axis": "epoch",
                        "step": epoch,
                        "value": _safe_float(event.get("val_metric")),
                        "value_type": "float",
                        "status": status,
                        "source_file": source_file,
                    }
                )
    return rows


