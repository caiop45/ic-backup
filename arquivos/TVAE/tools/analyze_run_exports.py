def _write_csv(path: Path, rows: list[dict[str, Any]], fieldnames: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=fieldnames)
        writer.writeheader()
        for row in rows:
            writer.writerow({field: _to_csv_value(row.get(field)) for field in fieldnames})


def _write_tooltips_csv(path: Path) -> dict[str, dict[str, str]]:
    tooltips = _build_tooltips()
    fieldnames = [
        "metric_id",
        "metric_name",
        "metric_family",
        "description",
        "preferred_direction",
        "lower_is_better",
    ]
    rows = [dict(item) for item in (tooltips.values())]
    _write_csv(path, rows, fieldnames)
    return tooltips


