def analyze_run_exports(
    *,
    run_dir: Path,
    metrics_export_json: Path | None = None,
    training_export_json: Path | None = None,
    output_dir: Path | None = None,
    analyze_metrics: bool = True,
    analyze_training: bool = True,
    strict: bool = False,
    no_plots: bool = False,
) -> dict[str, Any]:
    run_dir = Path(run_dir)
    output_dir = Path(output_dir) if output_dir is not None else run_dir / ANALYSIS_DIR_NAME
    output_dir.mkdir(parents=True, exist_ok=True)
    figures_dir = output_dir / OUTPUT_FIG_DIR
    figures_dir.mkdir(parents=True, exist_ok=True)

    output_json = output_dir / OUTPUT_JSON
    summary_csv = output_dir / OUTPUT_SUMMARY_CSV
    metrics_csv = output_dir / OUTPUT_METRICS_CSV
    training_csv = output_dir / OUTPUT_TRAINING_CSV
    tooltips_csv = output_dir / OUTPUT_TOOLTIPS_CSV
    html_report = output_dir / OUTPUT_HTML

    if metrics_export_json is None:
        metrics_export_json = run_dir / "metrics" / "metrics_export.json"
    if training_export_json is None:
        training_export_json = run_dir / "training" / "training_export.json"

    metrics_bundle: Mapping[str, Any] | None = None
    training_bundle: Mapping[str, Any] | None = None
    metrics_sections: Mapping[str, Mapping[str, Any]] = {}
    training_sections: Mapping[str, Mapping[str, Any]] = {}
    metrics_generated_at = None
    training_generated_at = None

    if analyze_metrics:
        if not metrics_export_json.exists():
            msg = f"missing metrics export: {metrics_export_json}"
            if strict:
                raise FileNotFoundError(msg)
            print(f"[analyze] warning: {msg}")
        else:
            metrics_bundle = _read_json(metrics_export_json)
            metrics_sections = _flatten_sections(metrics_bundle)
            metrics_generated_at = metrics_bundle.get("generated_at")
    if analyze_training:
        if not training_export_json.exists():
            msg = f"missing training export: {training_export_json}"
            if strict:
                raise FileNotFoundError(msg)
            print(f"[analyze] warning: {msg}")
        else:
            training_bundle = _read_json(training_export_json)
            training_sections = _flatten_sections(training_bundle)
            training_generated_at = training_bundle.get("generated_at")

    metrics_rows: list[dict[str, Any]] = []
    metric_summary_rows: list[dict[str, Any]] = []
    training_rows: list[dict[str, Any]] = []
    if analyze_metrics and metrics_bundle is not None:
        metrics_rows, metric_summary_rows = _collect_metric_comparison_rows(metrics_sections)
